def get_random_rp_phrase(action: str, sender: str, target: str) -> Optional[str]:
    """Returns a formatted random RP phrase from the library."""
    action_key = ACTION_ALIASES.get(action.lower().strip(), action.lower().strip())
    templates = RP_ACTIONS.get(action_key)
    if not templates:
        return None
    tpl = random.choice(templates)
    return tpl.format(sender, target)


def detect_rp_command(text: str) -> Optional[Tuple[str, str]]:
    """Detects if message starts with an RP command. Returns (canonical_action, remaining_text)."""
    if not text:
        return None

    cleaned = text.strip()
    # Check multi-word aliases first
    for alias, canon in sorted(ACTION_ALIASES.items(), key=lambda x: len(x[0]), reverse=True):
        pattern = rf"^[\.\!\/]?{re.escape(alias)}(\b|\n|\s|$)([\s\S]*)"
        m = re.match(pattern, cleaned, flags=re.IGNORECASE)
        if m:
            rest = m.group(2).strip()
            return canon, rest

    return None
